-- PostgreSQL schema. Applied transactionally by database/manage.py.
CREATE SEQUENCE operator_id_seq;
CREATE TABLE operator (
    operator_id VARCHAR(10) PRIMARY KEY DEFAULT
        ('OP' || lpad(nextval('operator_id_seq')::text, 3, '0')),
    legal_name VARCHAR(256) UNIQUE NOT NULL,
    brand_name VARCHAR(256) UNIQUE NOT NULL,
    brand_email VARCHAR(256) UNIQUE NOT NULL,
    tax_id VARCHAR(30) UNIQUE NOT NULL
);

CREATE TABLE account (
    account_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(256) UNIQUE NOT NULL,
    phone VARCHAR(20) UNIQUE NOT NULL,
    stat VARCHAR(20) NOT NULL DEFAULT 'Active'
        CHECK (stat IN ('Active', 'Inactive', 'Suspended', 'Deleted')),
    create_at DATE NOT NULL DEFAULT CURRENT_DATE,
    acc_password VARCHAR(256) NOT NULL
);

CREATE TABLE person (
    person_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    person_name VARCHAR(256) NOT NULL,
    date_of_birth DATE NOT NULL,
    gov_id_num VARCHAR(50) UNIQUE,
    account_id INTEGER UNIQUE NOT NULL REFERENCES account ON DELETE CASCADE
);
CREATE TABLE staff (
    staff_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    person_id INTEGER UNIQUE NOT NULL REFERENCES person ON DELETE CASCADE,
    hire_date DATE NOT NULL,
    operator_id VARCHAR(10) NOT NULL REFERENCES operator ON DELETE CASCADE
);
CREATE TABLE passenger (
    passenger_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    person_id INTEGER UNIQUE NOT NULL REFERENCES person ON DELETE CASCADE
);
CREATE TABLE station (
    station_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    city VARCHAR(256) NOT NULL,
    active_flag VARCHAR(256) DEFAULT 'Active'
        CHECK (active_flag IN ('Active', 'Inactive', 'Maintenance')),
    station_name VARCHAR(256) UNIQUE NOT NULL,
    latitude NUMERIC(9,6) NOT NULL,
    longtitude NUMERIC(9,6) NOT NULL,
    province VARCHAR(256) NOT NULL,
    address_station VARCHAR(256) NOT NULL,
    operator_id VARCHAR(10) NOT NULL REFERENCES operator ON DELETE CASCADE
);
CREATE TABLE pickupdropoff (
    point_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trans_type VARCHAR(20) NOT NULL CHECK (trans_type IN ('Pick Up', 'Drop Off', 'Both'))
);
CREATE TABLE haspoint (
    station_id INTEGER NOT NULL REFERENCES station ON DELETE CASCADE,
    point_id INTEGER NOT NULL REFERENCES pickupdropoff ON DELETE CASCADE,
    PRIMARY KEY (station_id, point_id)
);
CREATE TABLE bus (
    bus_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plate_number VARCHAR(256) UNIQUE NOT NULL,
    bus_active_flag VARCHAR(256) DEFAULT 'Active',
    capacity INTEGER NOT NULL CHECK (capacity > 0),
    vehicle_type VARCHAR(256) CHECK (vehicle_type IN ('Sleeper', 'Seater', 'Limousine')),
    operator_id VARCHAR(10) NOT NULL REFERENCES operator ON DELETE CASCADE
);
CREATE TABLE routetrip (
    route_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    default_duration_time TIME NOT NULL,
    distance INTEGER,
    station_id INTEGER NOT NULL REFERENCES station ON DELETE CASCADE,
    arrival_station INTEGER NOT NULL REFERENCES station ON DELETE CASCADE,
    operator_id VARCHAR(10) NOT NULL REFERENCES operator ON DELETE CASCADE,
    CHECK (station_id <> arrival_station)
);
CREATE TABLE trip (
    trip_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_status VARCHAR(256) NOT NULL DEFAULT 'Scheduled'
        CHECK (trip_status IN ('Scheduled', 'Departed', 'Arrived', 'Cancelled')),
    service_date TIMESTAMP NOT NULL,
    arrival_datetime TIMESTAMP,
    bus_id INTEGER NOT NULL REFERENCES bus ON DELETE CASCADE,
    route_id INTEGER NOT NULL REFERENCES routetrip ON DELETE CASCADE,
    UNIQUE (route_id, bus_id, service_date)
);
CREATE TABLE fare (
    fare_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    currency VARCHAR(20) DEFAULT 'VND',
    discount DOUBLE PRECISION DEFAULT 0,
    valid_from DATE NOT NULL,
    valid_to DATE NOT NULL,
    taxes DOUBLE PRECISION DEFAULT 0,
    route_id INTEGER NOT NULL REFERENCES routetrip ON DELETE CASCADE,
    surcharges INTEGER DEFAULT 0,
    base_fare INTEGER,
    seat_price INTEGER NOT NULL CHECK (seat_price >= 0),
    seat_class VARCHAR(20) NOT NULL CHECK (seat_class IN ('VIP', 'Standard', 'Economy')),
    CHECK (valid_from <= valid_to)
);
CREATE TABLE booking (
    booking_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    currency VARCHAR(20) NOT NULL,
    total_amount INTEGER DEFAULT 0,
    account_id INTEGER NOT NULL REFERENCES account ON DELETE CASCADE,
    operator_id VARCHAR(10) NOT NULL REFERENCES operator ON DELETE CASCADE,
    booking_status VARCHAR(20) NOT NULL DEFAULT 'Active'
        CHECK (booking_status IN ('Active', 'Cancelled', 'Completed')),
    admin_note VARCHAR(512),
    created_at TIMESTAMP NOT NULL DEFAULT LOCALTIMESTAMP
);
CREATE SEQUENCE ticket_serial_seq START WITH 10000000 MAXVALUE 99999999;
CREATE TABLE ticket (
    ticket_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_id INTEGER NOT NULL REFERENCES trip ON DELETE CASCADE,
    account_id INTEGER NOT NULL REFERENCES account ON DELETE CASCADE,
    booking_id INTEGER NOT NULL REFERENCES booking ON DELETE CASCADE,
    fare_id INTEGER NOT NULL REFERENCES fare ON DELETE CASCADE,
    qr_code_link VARCHAR(256),
    ticket_status VARCHAR(256) NOT NULL DEFAULT 'Issued'
        CHECK (ticket_status IN ('Used', 'Issued', 'Refunded', 'Cancelled')),
    seat_price INTEGER NOT NULL,
    seat_code VARCHAR(10) NOT NULL,
    serial_number INTEGER UNIQUE NOT NULL DEFAULT nextval('ticket_serial_seq')
);
-- Refunding/cancelling frees the seat while retaining the original ticket.
CREATE UNIQUE INDEX uq_ticket_active_trip_seat ON ticket(trip_id, seat_code)
    WHERE ticket_status IN ('Issued', 'Used');
CREATE INDEX idx_trip_service_date ON trip(service_date);
CREATE INDEX idx_ticket_booking ON ticket(booking_id);
CREATE INDEX idx_ticket_account ON ticket(account_id);
CREATE INDEX idx_fare_route ON fare(route_id);
CREATE TABLE seed_history (
    version TEXT PRIMARY KEY,
    applied_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
